function conv(s,P){
  for(const [k,v] of P) if(s.indexOf(k)>-1) s=s.split(k).join(v);
  return s.replace(/[۰-۹]/g,d=>"۰۱۲۳۴۵۶۷۸۹".indexOf(d)).replace(/،/g,",");
}
